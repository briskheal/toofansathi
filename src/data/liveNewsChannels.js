// Helper to find the best matching state based on district/state string from GPS
export function getChannelsForLocation(stateName) {
  if (!stateName) return LIVE_NEWS_REGIONS[0]; // Default to Odisha

  const query = stateName.toLowerCase().trim();

  // Check direct matches
  if (query.includes('odisha') || query.includes('orissa')) {
    return LIVE_NEWS_REGIONS.find((r) => r.state === 'Odisha') || LIVE_NEWS_REGIONS[0];
  }
  if (query.includes('bengal') || query.includes('kolkata')) {
    return LIVE_NEWS_REGIONS.find((r) => r.state === 'West Bengal') || LIVE_NEWS_REGIONS[0];
  }
  if (query.includes('andhra') || query.includes('telangana')) {
    return LIVE_NEWS_REGIONS.find((r) => r.state === 'Andhra Pradesh') || LIVE_NEWS_REGIONS[0];
  }
  if (query.includes('gujarat')) {
    return LIVE_NEWS_REGIONS.find((r) => r.state === 'Gujarat') || LIVE_NEWS_REGIONS[0];
  }
  if (query.includes('tamil')) {
    return LIVE_NEWS_REGIONS.find((r) => r.state === 'Tamil Nadu') || LIVE_NEWS_REGIONS[0];
  }

  // Fallback to National DD News
  return LIVE_NEWS_REGIONS.find((r) => r.state === 'National') || LIVE_NEWS_REGIONS[0];
}
